"""Value objects for the knowledge layer.

Everything here describes what is on disk. Nothing is persisted: a catalogue
is produced by walking the directory at call time, so these types are the
shape of an answer, never the shape of a row.
"""

from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass, field
from typing import Any

ACTOR_AGENT = "agent"
ACTOR_USER = "user"


@dataclass(frozen=True)
class CollectionEntry:
    """One collection, as the top level of the catalogue shows it."""

    #: The collection resource's identity. Every route that addresses this
    #: collection takes it, so the catalogue has to carry it — the page cannot
    #: derive it from a name any more, and asking per row would be the N+1 the
    #: catalogue exists to avoid.
    #:
    #: Empty for a directory on disk that no row claims: the catalogue is
    #: generated by walking the tree, so it can see such a folder, and the
    #: registry join is what keeps one out of the list a caller gets.
    uid: str
    name: str
    #: First paragraph of the collection's ``README.md``; empty when absent.
    description: str
    #: Mechanical findings: only broken links ("Check every link in a collection").
    finding_count: int = 0
    findings: tuple[Finding, ...] = ()
    #: The collection directory's absolute path, so a surface can reveal it
    #: ("Return absolute paths on reads"); empty where it was not read.
    folder_path: str = ""
    #: When a document in the collection was last written (ISO 8601, UTC);
    #: ``None`` when it holds none.
    updated_at: str | None = None
    #: A linked folder the person keeps with their own tools, which Coffer only
    #: shares with the agents (ADR
    #: linked-knowledge-folders-are-read-only-and-machine-local).
    linked: bool = False
    #: The Markdown files in the collection, its README left out.
    note_count: int = 0
    #: The file whose rules agents follow in it, relative to the collection: what
    #: its README declares as ``rules``, else the first of ``AGENTS.md``,
    #: ``CLAUDE.md`` and ``README.md`` at its root; empty when none ("Let each
    #: collection declare its own rules").
    rules_file: str = ""
    #: The page an agent starts from (its README's ``entry``); empty when none.
    entry_file: str = ""
    #: Where Coffer writes uploads and dropped files (its README's ``uploads``,
    #: ``sources`` by default); empty for a linked folder.
    uploads_dir: str = ""


@dataclass(frozen=True)
class DirectoryEntry:
    """A subdirectory inside a collection — filed by a person or an agent."""

    #: Path relative to the knowledge root, e.g. ``shopee/account``.
    path: str
    name: str
    file_count: int


@dataclass(frozen=True)
class FileEntry:
    """A file as the catalogue lists it: enough to choose without reading."""

    #: Path relative to the knowledge root, e.g. ``shopee/pages/gateway.md``.
    path: str
    title: str
    description: str
    actor: str
    updated_at: str


@dataclass(frozen=True)
class CatalogueLevel:
    """One level of one collection — what a human surface pages through."""

    path: str
    directories: tuple[DirectoryEntry, ...] = field(default_factory=tuple)
    files: tuple[FileEntry, ...] = field(default_factory=tuple)


@dataclass(frozen=True)
class LinkRef:
    """A link in a file's body and the one file it resolves to: a
    ``[[target]]`` (``kind`` ``wiki``) or a standard Markdown link by relative
    path (``kind`` ``path``, ``target`` as written). ``path`` is ``None`` when
    it is dead or ambiguous (``ambiguous`` says which), or leaves the
    knowledge root (``outside``)."""

    target: str
    path: str | None = None
    ambiguous: bool = False
    kind: str = "wiki"
    outside: bool = False


@dataclass(frozen=True)
class Finding:
    """One broken link in a collection (spec knowledge "Check every link in a
    collection").

    ``path`` is the file it is in; ``target`` the link as written; ``others``
    the files an ambiguous link could mean.
    """

    kind: str
    path: str
    target: str | None = None
    others: tuple[str, ...] = ()


@dataclass(frozen=True)
class KnowledgeFile:
    """A file's full content plus the on-disk truth a surface must expose."""

    path: str
    title: str
    description: str
    actor: str
    created_at: str
    updated_at: str
    body: str
    #: Absolute path of the ``.md`` file (spec knowledge "Return absolute paths
    #: on reads").
    file_path: str
    #: Absolute path of its containing folder.
    folder_path: str
    #: Every link in its body, each resolved to the file it names.
    links: tuple[LinkRef, ...] = ()
    #: An uploaded source's original file name (its ``original``), and where
    #: that file is on this Mac — ``None`` on any other Mac.
    original: str = ""
    original_path: str | None = None
    #: The body as a reader should see it when the file still carries an
    #: export's own frontmatter or storage markers; ``None`` when it reads as
    #: it is (spec knowledge "Import a Confluence page as a readable source
    #: with its attachments").
    readable_body: str | None = None
    #: Where an imported source came from (``system``, ``url``, ``page_id``,
    #: ``version``, ``fetched_at``…); empty for anything else.
    origin: Mapping[str, str] = field(default_factory=dict)
    #: An import's report as its frontmatter keeps it; empty when none.
    import_report: Mapping[str, Any] = field(default_factory=dict)


@dataclass(frozen=True)
class GrepMatch:
    path: str
    line_number: int
    line: str


@dataclass(frozen=True)
class GrepOutcome:
    matches: tuple[GrepMatch, ...] = field(default_factory=tuple)
    truncated: bool = False


@dataclass(frozen=True)
class Submission:
    """What became of one piece of submitted material: the document it became."""

    collection: str
    title: str
    document: KnowledgeFile
